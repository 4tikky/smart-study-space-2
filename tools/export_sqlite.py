"""Export legacy SQLite data to an administrator-only Supabase SQL import.

Does not connect to Supabase or change SQLite. The generated SQL may contain
private stream credentials and must never be committed or put in frontend/public.
"""
import argparse
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def literal(value):
    if value is None:
        return 'null'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def export(database, target):
    statements = ['-- PRIVATE import: execute once in Supabase SQL Editor after the schema migration.', 'begin;']
    with sqlite3.connect(database.resolve().as_uri() + '?mode=ro', uri=True) as db:
        db.row_factory = sqlite3.Row
        counts = {}
        for table in ('floors', 'zones', 'cameras', 'history'):
            counts[table] = 0
            for source in db.execute(f'SELECT * FROM {table} ORDER BY id'):
                row = dict(source)
                url = row.pop('stream_url', None)
                row.pop('occupancy', None)  # Generated by PostgreSQL from the actual counts.
                if 'enabled' in row:
                    row['enabled'] = bool(row['enabled'])
                columns = ','.join(row)
                statements.append(f'insert into public.{table}({columns}) values({",".join(literal(v) for v in row.values())});')
                if table == 'cameras' and url:
                    statements.append(f'insert into public.camera_sources(camera_id,stream_url) values({row["id"]},{literal(url)});')
                counts[table] += 1
            statements.append(f"select setval(pg_get_serial_sequence('public.{table}','id'),greatest(coalesce((select max(id) from public.{table}),1),1),exists(select 1 from public.{table}));")
        for row in db.execute("SELECT key,value FROM preferences WHERE key IN ('settings','metadata')"):
            value = json.loads(row['value'])
            if row['key'] == 'settings':
                assignments = ','.join(f'{key}={int(value[key])}' for key in ('limited_at','full_at','retention_days'))
                statements.append(f'update public.app_settings set {assignments} where id=1;')
            else:
                statements.append(f'update public.training_metadata set value={literal(json.dumps(value))}::jsonb where id=1;')
    statements += ['commit;', '-- Review retention_days before starting cloud monitoring; old history is pruned on the next write.']
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(statements) + '\n', encoding='utf-8')
    return counts


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--database', type=Path, default=ROOT / 'backend/data/study-space.sqlite3')
    parser.add_argument('--output', type=Path, default=ROOT / '.local/sqlite-import.sql')
    args = parser.parse_args()
    print(json.dumps({'exported': export(args.database, args.output), 'output': str(args.output)}))
