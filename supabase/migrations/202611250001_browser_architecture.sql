create table public.operators (
  user_id uuid primary key references auth.users(id) on delete cascade
);
alter table public.operators enable row level security;
create policy own_membership on public.operators for select to authenticated using (user_id = (select auth.uid()));
grant select on public.operators to authenticated;

create function public.is_operator() returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.operators where user_id = (select auth.uid()));
$$;
revoke all on function public.is_operator() from public;
grant execute on function public.is_operator() to anon, authenticated;

create table public.floors (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) between 1 and 100),
  description text not null default '' check (length(description) <= 240), enabled boolean not null default true
);
create table public.zones (
  id bigint generated by default as identity primary key,
  floor_id bigint not null references public.floors(id) on delete cascade,
  name text not null check (length(trim(name)) between 1 and 100), description text not null default '' check (length(description) <= 240),
  outlets integer check (outlets between 0 and 1000), layout_row integer check (layout_row between 1 and 12),
  layout_col integer check (layout_col between 1 and 6),
  check ((layout_row is null) = (layout_col is null)), unique(floor_id, name), unique(floor_id, layout_row, layout_col), unique(id, floor_id)
);
create table public.cameras (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) between 1 and 100),
  kind text not null check (kind in ('browser', 'stream')), floor_id bigint not null references public.floors(id) on delete cascade,
  zone_id bigint, enabled boolean not null default true, interval_ms integer not null default 750 check (interval_ms between 250 and 10000),
  foreign key(zone_id, floor_id) references public.zones(id, floor_id) deferrable initially deferred
);
create unique index one_camera_per_scope on public.cameras(floor_id, coalesce(zone_id, 0)) where enabled;
-- Gateway URLs may contain credentials; they never appear in the public tables or Realtime payloads.
create table public.camera_sources (
  camera_id bigint primary key references public.cameras(id) on delete cascade,
  stream_url text not null check (length(stream_url) <= 2048)
);
create table public.app_settings (
  id integer primary key default 1 check (id = 1), limited_at integer not null default 65 check (limited_at between 1 and 99),
  full_at integer not null default 90 check (full_at between 1 and 100),
  retention_days integer not null default 7 check (retention_days between 1 and 3650), check (limited_at < full_at)
);
insert into public.app_settings(id) values(1);
create table public.training_metadata (id integer primary key default 1 check(id = 1), value jsonb not null default '{}'::jsonb check (octet_length(value::text) <= 4096));
insert into public.training_metadata(id) values(1);

create table public.history (
  id bigint generated by default as identity primary key, session_id text not null check(length(session_id) <= 100),
  timestamp timestamptz not null default now(), source text not null check(source in ('image', 'video', 'live')),
  floor_id bigint, floor_name text, zone_name text, camera_id bigint, camera_name text,
  total integer not null check(total between 0 and 300), empty integer not null check(empty >= 0), occupied integer not null check(occupied >= 0),
  occupancy double precision generated always as (case when total > 0 then occupied::double precision / total else null end) stored,
  elapsed_ms double precision not null check(elapsed_ms >= 0 and elapsed_ms < 3600000),
  details jsonb check(octet_length(details::text) <= 131072), created_by uuid references auth.users(id) on delete set null,
  check(total = empty + occupied)
);
create index history_time on public.history(timestamp desc, id desc);
create index history_camera_time on public.history(camera_id, timestamp desc);
create index history_floor_time on public.history(floor_id, timestamp desc);
create unique index history_once_nonlive on public.history(session_id) where source <> 'live';
create table public.camera_leases (
  camera_id bigint primary key references public.cameras(id) on delete cascade,
  session_id uuid not null, owner_id uuid not null references auth.users(id) on delete cascade, expires_at timestamptz not null
);
create table public.camera_reports (
  camera_id bigint primary key references public.cameras(id) on delete cascade,
  total integer not null check(total between 0 and 300), empty integer not null check(empty >= 0), occupied integer not null check(occupied >= 0),
  occupancy double precision generated always as (case when total > 0 then occupied::double precision / total else null end) stored,
  observed_at timestamptz not null, expires_at timestamptz not null, check(total = empty + occupied)
);

-- Default deny. A successful Auth signup alone never grants operator privileges.
do $$ declare t text; begin
  foreach t in array array['floors','zones','cameras','app_settings','camera_reports'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy public_read on public.%I for select to anon, authenticated using (true)', t);
    execute format('grant select on public.%I to anon, authenticated', t);
  end loop;
  foreach t in array array['floors','zones','cameras','app_settings','camera_sources','training_metadata'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy operator_write on public.%I for all to authenticated using ((select public.is_operator())) with check ((select public.is_operator()))', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;
alter table public.history enable row level security;
alter table public.camera_leases enable row level security;
create policy operator_history on public.history for select to authenticated using ((select public.is_operator()));
create policy operator_leases on public.camera_leases for select to authenticated using ((select public.is_operator()));
grant select on public.history, public.camera_leases to authenticated;
grant usage, select on all sequences in schema public to authenticated;
-- Reports, leases and history can only be written via checked RPCs, never direct table writes.
revoke insert, update, delete on public.camera_reports, public.camera_leases, public.history, public.operators from anon, authenticated;

create function public.prune_history() returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
  delete from public.history where timestamp < now() - make_interval(days => (select retention_days from public.app_settings where id=1));
end $$;

create function public.record_detection(p_session text, p_source text, p_summary jsonb, p_elapsed double precision, p_details jsonb default null)
returns bigint language plpgsql security definer set search_path = '' as $$
declare result bigint;
begin
  if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
  if (select count(*) from public.history where created_by=auth.uid() and timestamp > now()-interval '1 minute') >= 30 then
    raise exception 'Terlalu banyak catatan. Tunggu sebentar.';
  end if;
  perform public.prune_history();
  insert into public.history(session_id,source,total,empty,occupied,elapsed_ms,details,created_by)
  values(p_session,p_source,(p_summary->>'total')::integer,(p_summary->>'empty')::integer,(p_summary->>'occupied')::integer,p_elapsed,p_details,auth.uid())
  on conflict(session_id) where source <> 'live' do nothing returning id into result;
  if result is null then select id into result from public.history where session_id=p_session and created_by=auth.uid() limit 1; end if;
  if result is null then raise exception 'ID sesi telah digunakan'; end if;
  return result;
end $$;

create function public.claim_camera(p_camera bigint, p_session uuid) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
  if not exists(select 1 from public.cameras c join public.floors f on f.id=c.floor_id where c.id=p_camera and c.enabled and f.enabled) then
    raise exception 'Kamera atau lantai tidak aktif';
  end if;
  insert into public.camera_leases(camera_id,session_id,owner_id,expires_at) values(p_camera,p_session,auth.uid(),now()+interval '60 seconds')
  on conflict(camera_id) do update set session_id=excluded.session_id,owner_id=excluded.owner_id,expires_at=excluded.expires_at
  where public.camera_leases.expires_at <= now() or (public.camera_leases.owner_id=auth.uid() and public.camera_leases.session_id=p_session);
  if not found then raise exception 'Kamera sedang digunakan sesi lain'; end if;
  delete from public.camera_reports where camera_id=p_camera;
end $$;

create function public.publish_camera(p_camera bigint, p_session uuid, p_summary jsonb, p_elapsed double precision)
returns void language plpgsql security definer set search_path = '' as $$
declare cam public.cameras; last_seen timestamptz;
begin
  if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
  select c.* into cam from public.cameras c join public.floors f on f.id=c.floor_id where c.id=p_camera and c.enabled and f.enabled;
  if not found then raise exception 'Kamera atau lantai tidak aktif'; end if;
  update public.camera_leases set expires_at=now()+interval '60 seconds'
    where camera_id=p_camera and owner_id=auth.uid() and session_id=p_session and expires_at>now();
  if not found then raise exception 'Sesi kamera kedaluwarsa. Mulai kembali pemantauan.'; end if;
  select observed_at into last_seen from public.camera_reports where camera_id=p_camera;
  if last_seen > now()-interval '10 seconds' then return; end if;
  insert into public.camera_reports(camera_id,total,empty,occupied,observed_at,expires_at)
  values(p_camera,(p_summary->>'total')::integer,(p_summary->>'empty')::integer,(p_summary->>'occupied')::integer,now(),now()+interval '45 seconds')
  on conflict(camera_id) do update set total=excluded.total,empty=excluded.empty,occupied=excluded.occupied,observed_at=excluded.observed_at,expires_at=excluded.expires_at;
  if not exists(select 1 from public.history where camera_id=p_camera and timestamp>now()-interval '1 minute') then
    perform public.prune_history();
    insert into public.history(session_id,source,floor_id,floor_name,zone_name,camera_id,camera_name,total,empty,occupied,elapsed_ms,created_by)
    select p_session::text,'live',cam.floor_id,f.name,z.name,cam.id,cam.name,(p_summary->>'total')::integer,(p_summary->>'empty')::integer,(p_summary->>'occupied')::integer,p_elapsed,auth.uid()
    from public.floors f left join public.zones z on z.id=cam.zone_id where f.id=cam.floor_id;
  end if;
end $$;

create function public.release_camera(p_camera bigint, p_session uuid) returns void language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
  delete from public.camera_leases where camera_id=p_camera and session_id=p_session and owner_id=auth.uid();
  if found then delete from public.camera_reports where camera_id=p_camera; end if;
end $$;

create function public.invalidate_camera() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  delete from public.camera_reports where camera_id=new.id;
  delete from public.camera_leases where camera_id=new.id;
  return new;
end $$;
create trigger invalidate_camera after update on public.cameras for each row execute function public.invalidate_camera();
create function public.invalidate_floor() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if not new.enabled then
    delete from public.camera_reports where camera_id in(select id from public.cameras where floor_id=new.id);
    delete from public.camera_leases where camera_id in(select id from public.cameras where floor_id=new.id);
  end if;
  return new;
end $$;
create trigger invalidate_floor after update on public.floors for each row execute function public.invalidate_floor();

create function public.public_snapshot() returns jsonb language sql stable security invoker set search_path = '' as $$
select jsonb_build_object('server_now',now(),
 'floors',coalesce((select jsonb_agg(f order by id) from public.floors f where enabled),'[]'::jsonb),
 'zones',coalesce((select jsonb_agg(z order by z.id) from public.zones z join public.floors f on f.id=z.floor_id where f.enabled),'[]'::jsonb),
 'cameras',coalesce((select jsonb_agg(c order by c.id) from public.cameras c join public.floors f on f.id=c.floor_id where c.enabled and f.enabled),'[]'::jsonb),
 'reports',coalesce((select jsonb_agg(r) from public.camera_reports r where expires_at>now()),'[]'::jsonb),
 'settings',(select to_jsonb(s) from public.app_settings s where id=1));
$$;

create function public.get_analytics(p_start date, p_end date) returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare result jsonb;
begin
 if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
 if p_start>p_end then raise exception 'Tanggal awal harus sebelum tanggal akhir'; end if;
 with records as (
   select *,timestamp at time zone 'Asia/Jakarta' as local from public.history where source='live' and camera_id is not null
   and timestamp >= p_start::timestamp at time zone 'Asia/Jakarta'
   and timestamp < (p_end+1)::timestamp at time zone 'Asia/Jakarta'
 ), groups as (
   select category,label,count(*) as samples,round(avg(empty),2) as empty,round(avg(occupancy)::numeric*100,2) as occupancy
   from records cross join lateral (values
    ('trend',to_char(local,case when p_start=p_end then 'YYYY-MM-DD HH24:00' else 'YYYY-MM-DD' end)),
    ('floors',floor_name),('hourly',to_char(local,'HH24:00')),
    ('daily',(array['1 Sen','2 Sel','3 Rab','4 Kam','5 Jum','6 Sab','7 Min'])[extract(isodow from local)::integer])
   ) labels(category,label) where label is not null group by category,label
 ), points as (select category,label,jsonb_build_object('label',label,'samples',samples,'empty',empty,'occupancy',occupancy) as point,occupancy from groups)
 select jsonb_build_object('count',(select count(*) from records),'average',(select round(avg(occupancy)::numeric*100,2) from records),
 'trend',coalesce((select jsonb_agg(point order by label) from points where category='trend'),'[]'::jsonb),
 'floors',coalesce((select jsonb_agg(point order by label) from points where category='floors'),'[]'::jsonb),
 'hourly',coalesce((select jsonb_agg(point order by label) from points where category='hourly'),'[]'::jsonb),
 'daily',coalesce((select jsonb_agg(point order by label) from points where category='daily'),'[]'::jsonb),
 'peak',(select point from points where category='hourly' and occupancy is not null order by occupancy desc,label limit 1)) into result;
 return result;
end $$;

create function public.save_camera(p_camera jsonb, p_id bigint default null) returns jsonb language plpgsql security definer set search_path = '' as $$
declare cam public.cameras; url text;
begin
 if not public.is_operator() then raise exception 'Akses operator diperlukan' using errcode='42501'; end if;
 if p_id is null then
  insert into public.cameras(name,kind,floor_id,zone_id,interval_ms,enabled)
   values(trim(p_camera->>'name'),p_camera->>'kind',(p_camera->>'floor_id')::bigint,(p_camera->>'zone_id')::bigint,
    (p_camera->>'interval_ms')::integer,(p_camera->>'enabled')::boolean) returning * into cam;
 else
  update public.cameras set name=trim(p_camera->>'name'),kind=p_camera->>'kind',floor_id=(p_camera->>'floor_id')::bigint,
   zone_id=(p_camera->>'zone_id')::bigint,interval_ms=(p_camera->>'interval_ms')::integer,enabled=(p_camera->>'enabled')::boolean
   where id=p_id returning * into cam;
  if not found then raise exception 'Kamera tidak ditemukan'; end if;
 end if;
 if cam.kind='stream' then
  url=nullif(trim(p_camera->>'stream_url'),'');
  if url is null then select stream_url into url from public.camera_sources where camera_id=cam.id; end if;
  if url is null or url !~* '^(rtsp|rtsps|http|https)://' then raise exception 'Masukkan URL stream atau media gateway yang valid'; end if;
  insert into public.camera_sources(camera_id,stream_url) values(cam.id,url) on conflict(camera_id) do update set stream_url=excluded.stream_url;
 else delete from public.camera_sources where camera_id=cam.id;
 end if;
 return to_jsonb(cam);
end $$;

