 public.get_analytics(date,date), public.public_snapshot(), public.invalidate_camera(), public.invalidate_floor(), public.save_camera(jsonb,bigint) from public;
grant execute on function public.prune_history(), public.record_detection(text,text,jsonb,double precision,jsonb),
